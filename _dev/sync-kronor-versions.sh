#!/usr/bin/env bash
# Pin the library's build to the package versions Kronor uses, for the CI job that
# builds and tests it with them.
#
# Kronor uses the smart-csv library with its own, newer dependencies (for example
# morpheus-graphql-core 0.28 and aeson 2.3 built with +ordered-keymap), while the
# runner keeps cabal.project.freeze. This writes:
#   cabal.project.kronor         the library only, with Kronor's compiler,
#                                package repository and allow-newer entries
#   cabal.project.kronor.freeze  Kronor's versions of the packages the library
#                                and its tests use, and nothing else: this
#                                repository is public, Kronor's is not
#
# It solves the build with Kronor's whole freeze file, then lets cabal freeze the
# result, so it needs Kronor's GHC: run it from Kronor's dev shell.
#
# Usage: _dev/sync-kronor-versions.sh <path to a Kronor checkout> [git ref, default origin/master]
# Fetch first: the files are read from the ref, not from the working tree.
set -euo pipefail

KRONOR_DIR="${1:?usage: $0 <path to a Kronor checkout> [git ref]}"
REF="${2:-origin/master}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROJECT="$ROOT/cabal.project.kronor"
FREEZE="$PROJECT.freeze"

kronor_file() { git -C "$KRONOR_DIR" show "$REF:$1"; }

kronor_file cabal.project.freeze > /dev/null || { echo "No cabal.project.freeze at $REF in $KRONOR_DIR" >&2; exit 1; }

# Kronor's flake names its compiler as haskell.nix does: ghc9124 is GHC 9.12.4.
GHC_VERSION="$(kronor_file flake.nix | sed -nE 's/.*compiler-nix-name = "ghc([0-9])([0-9]{2})([0-9]+)".*/\1.\2.\3/p' | head -1)"
[ -n "$GHC_VERSION" ] || { echo "No compiler-nix-name in flake.nix at $REF" >&2; exit 1; }
command -v "ghc-$GHC_VERSION" > /dev/null || { echo "ghc-$GHC_VERSION is not on PATH; run this from Kronor's dev shell" >&2; exit 1; }

COMMIT="$(git -C "$KRONOR_DIR" log -1 --format='%h (%cs)' "$REF")"

write_project() {
    local allow_newer="$1"
    {
        echo "-- Generated by _dev/sync-kronor-versions.sh from Kronor $COMMIT."
        echo "-- Builds the library and its tests with Kronor's versions; see README."
        echo "-- Don't edit by hand: run the script again."
        echo
        echo "with-compiler: ghc-$GHC_VERSION"
        echo
        echo "packages: smart-csv"
        echo
        echo "tests: True"
        echo
        echo "repository github-kronor-haskell-packages"
        echo "  url: https://kronor-io.github.io/kronor-haskell-packages"
        echo "  secure: True"
        echo "  root-keys:"
        echo "    64307ca6c1cee780dd01e5e11193ba606b21fe1dd6a9102b838daff0c747eded"
        echo "    85a0bbddb3afe87449114e7b0622c9c80bd9164b5228dbc7db9fe66f3043f540"
        echo "    f344d0824b70101babfdea1e470b7388f6b8fc51b41186a627e98c71068a838c"
        echo
        echo "allow-newer:"
        echo "$allow_newer"
    } > "$PROJECT"
}

# Kronor's allow-newer entries (pkg:dep or *:dep), one per line, without comments.
ALL_ALLOW_NEWER="$(kronor_file cabal.project \
    | awk '/^allow-newer:/ { copying = 1; next } copying && /^[[:space:]]*$/ { exit } copying { print }' \
    | sed -E 's/--.*//; s/[[:space:],]//g' | grep -v '^$')"

# 1. Solve with Kronor's whole freeze file and every allow-newer entry.
write_project "$(echo "$ALL_ALLOW_NEWER" | sed 's/^/  /; s/$/,/')"
kronor_file cabal.project.freeze > "$FREEZE"
(cd "$ROOT" && cabal update --project-file=cabal.project.kronor > /dev/null)

# 2. Freeze the result: only the packages in the library's build plan remain.
(cd "$ROOT" && cabal freeze --project-file=cabal.project.kronor > /dev/null)

IN_PLAN="$(grep -oE 'any\.[A-Za-z0-9-]+' "$FREEZE" | sed 's/^any\.//' | sort -u)"

# 3. Add Kronor's flags for those packages. cabal freeze leaves out the flags of
# packages it found already built (Kronor's dev shell has them), but CI builds
# them from source and must use the same flags, such as aeson +ordered-keymap.
FLAGS="$(kronor_file cabal.project.freeze \
    | sed -nE 's/^[[:space:]]+([A-Za-z0-9-]+) ([+-][^,]*),?$/\1 \2/p' \
    | while read -r pkg flags; do
        if grep -qx "$pkg" <<< "$IN_PLAN" && ! grep -qE "^[[:space:]]+$pkg [+-]" "$FREEZE"; then
            echo "             $pkg $flags,"
        fi
    done)"
if [ -n "$FLAGS" ]; then
    awk -v flags="$FLAGS" '{ print } /^constraints:/ { print flags }' "$FREEZE" > "$FREEZE.tmp"
    mv "$FREEZE.tmp" "$FREEZE"
fi

# 4. Keep the allow-newer entries that concern a package in that plan.
KEPT="$(echo "$ALL_ALLOW_NEWER" | while IFS=: read -r pkg dep; do
    if { [ "$pkg" = "*" ] || grep -qx "$pkg" <<< "$IN_PLAN"; } && grep -qx "$dep" <<< "$IN_PLAN"; then
        echo "  $pkg:$dep,"
    fi
done)"
write_project "$KEPT"

echo "Wrote cabal.project.kronor (GHC $GHC_VERSION) and cabal.project.kronor.freeze ($(grep -c 'any\.' "$FREEZE") packages) from Kronor $COMMIT"
